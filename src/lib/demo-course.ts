let taskOrder = 0;
function t(
  nodeId: string,
  type: Task['type'],
  prompt: string,
  answerSpec: Task['answerSpec'],
  hints: string[],
  explanation: string,
  params?: Task['params']
): Task {
  return {
    id: `${M}-t${String(++taskOrder).padStart(2, '0')}`,
    nodeId,
    materialId: M,
    type,
    prompt,
    params,
    answerSpec,
    hints,
    explanation,
    orderIndex: taskOrder,
    createdAt: new Date(),
  };
}

