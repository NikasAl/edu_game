def num(tid, node, prompt, expr, params, hints, expl, tol=0.02):
    return dict(id=f'fm-{tid}', nodeId=node, materialId=M, type='numeric', prompt=prompt,
                params=[{'name': n, 'choices': v} for n, v in params],
                answerSpec={'kind': 'numeric', 'expr': expr, 'tolerance': tol},
                hints=hints, explanation=expl)

def ch(tid, node, prompt, options, correct, hints, expl):
    return dict(id=f'fm-{tid}', nodeId=node, materialId=M, type='choice', prompt=prompt,
                answerSpec={'kind': 'choice', 'options': options, 'correctIndex': correct},
                hints=hints, explanation=expl)

def ex(tid, node, prompt, value, alts, hints, expl):
    return dict(id=f'fm-{tid}', nodeId=node, materialId=M, type='exact', prompt=prompt,
                answerSpec={'kind': 'exact', 'value': value, 'alts': alts},
                hints=hints, explanation=expl)

