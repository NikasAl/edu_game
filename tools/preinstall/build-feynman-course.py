# ---------------------------------------------------------------- build
def build():
    regions = [{
        'id': rid, 'materialId': M, 'orderIndex': i, 'title': title, 'createdAt': CREATED,
    } for i, (rid, title) in enumerate(REGIONS)]

    nodes = []
    for i, (nid, rid, kind, title, form, ex_, mis, fq, kt, qsrc) in enumerate(NODES):
        nodes.append({
            'id': nid, 'materialId': M, 'regionId': rid, 'title': title,
            'formulation': form, 'example': ex_, 'misconception': mis,
            'feynmanQuestion': fq, 'keyTerms': kt, 'atomKind': kind,
            'sourceRef': QUOTES.get(qsrc, ''),
            'orderIndex': i, 'createdAt': CREATED,
        })

    edges = []
    for i, (f_, t_) in enumerate(HARD):
        edges.append({'id': f'fm-eh{i:02}', 'materialId': M, 'fromNodeId': f_, 'toNodeId': t_,
                      'kind': 'hard', 'orderIndex': i, 'createdAt': CREATED})
    for i, (f_, t_) in enumerate(SOFT):
        edges.append({'id': f'fm-es{i:02}', 'materialId': M, 'fromNodeId': f_, 'toNodeId': t_,
                      'kind': 'soft', 'orderIndex': len(HARD) + i, 'createdAt': CREATED})

    tasks = []
    for i, t in enumerate(TASKS):
        tasks.append({**t, 'orderIndex': i, 'createdAt': CREATED})

    payload = {
        'app': 'edu_game', 'kind': 'course', 'version': 1,
        'bundleId': str(uuid.uuid4()),
        'exportedAt': datetime.utcnow().isoformat() + 'Z',
        'title': 'Метод блокнота Фейнмана',
        'materials': [{
            'id': M, 'title': 'Метод блокнота Фейнмана',
            'description': 'Интерактивный курс о том, как учился Фейнман: выводить с нуля, объяснять просто, думать на бумаге и защищать своё внимание. Заодно показывает возможности приложения.',
            'sourceText': SOURCE_TEXT,
            'parentId': None, 'orderIndex': 0, 'createdAt': CREATED,
        }],
        'regions': regions, 'nodes': nodes, 'edges': edges, 'tasks': tasks,
    }
    with open(OUT, 'w') as f:
        json.dump(payload, f, ensure_ascii=False, indent=1)
    print('written:', OUT)
    print(f'materials={len(payload["materials"])} regions={len(regions)} nodes={len(nodes)} edges={len(edges)} tasks={len(tasks)}')

if __name__ == '__main__':
    build()
